import { TIER_LABEL } from "@/lib/format";
import type { EvidenceStatus, Owner, Tier, TierResult } from "@/lib/types";

// Text labels carry the meaning; color only reinforces it, so badges stay readable in print and for color-blind readers.
const TIER_STYLE: Record<Tier, string> = {
  instant: "border-emerald-300 bg-emerald-50 text-emerald-900",
  easy: "border-lime-300 bg-lime-50 text-lime-900",
  moderate: "border-amber-300 bg-amber-50 text-amber-900",
  high: "border-orange-300 bg-orange-50 text-orange-900",
  restricted: "border-red-300 bg-red-50 text-red-900",
};

function Pill({ className, title, children }: { className: string; title?: string; children: React.ReactNode }) {
  return (
    <span title={title} className={`inline-block whitespace-nowrap rounded border px-1.5 py-px text-xs font-medium ${className}`}>
      {children}
    </span>
  );
}

/** Confirmed tier when evidence settles it; otherwise the face-value tier marked unconfirmed, plus the worst case. */
export function TierBadge({ tier }: { tier: TierResult }) {
  if (tier.optimistic === tier.pessimistic) {
    return <Pill className={TIER_STYLE[tier.optimistic]}>{TIER_LABEL[tier.optimistic]}</Pill>;
  }
  return (
    <span className="inline-flex flex-wrap items-center gap-1.5">
      <Pill className={`${TIER_STYLE[tier.likely]} border-dashed`} title="What the agent found, but not all of it is confirmed by evidence">
        Likely {TIER_LABEL[tier.likely]} · unconfirmed
      </Pill>
      {tier.pessimistic !== tier.likely && <span className="text-xs text-zinc-600">could be up to {TIER_LABEL[tier.pessimistic]}</span>}
    </span>
  );
}

export const EVIDENCE: Record<EvidenceStatus, { label: string; style: string; meaning: string }> = {
  tested: { label: "Tested", style: "border-emerald-300 bg-emerald-50 text-emerald-900", meaning: "Observed first-hand by one of the agent's probes against the provider." },
  sourced: { label: "Sourced", style: "border-sky-300 bg-sky-50 text-sky-900", meaning: "Stated in a fetched page; the quoted text was checked to appear in that page." },
  inferred: { label: "Inferred", style: "border-amber-300 bg-amber-50 text-amber-900", meaning: "The agent's reasoning without direct support. Treat as likely, not confirmed." },
  unknown: { label: "Unknown", style: "border-zinc-300 bg-zinc-50 text-zinc-800", meaning: "Could not be determined." },
};

export function EvidenceBadge({ status }: { status: EvidenceStatus }) {
  const e = EVIDENCE[status];
  return (
    <Pill className={e.style} title={e.meaning}>
      {e.label}
    </Pill>
  );
}

export const OWNER: Record<Owner, { label: string; meaning: string }> = {
  agent: { label: "Agent", meaning: "Done by the agent; nothing for you to do." },
  agent_prepares: { label: "Agent prepares, you submit", meaning: "The agent drafted the values or text; you paste and submit them." },
  human: { label: "You", meaning: "Needs your login, identity, payment, or legal acceptance." },
};

export function CurationBadge({ curated }: { curated: boolean }) {
  return curated ? (
    <Pill className="border-emerald-300 bg-emerald-50 text-emerald-900" title="A person checked this version against sources or a setup attempt">
      Human-reviewed
    </Pill>
  ) : (
    <Pill className="border-zinc-300 bg-zinc-50 text-zinc-800" title="Generated by the agent; checked only by the automatic quote verifier">
      Agent-generated, not human-reviewed
    </Pill>
  );
}
